#!/usr/bin/env python3
"""Import selected NPC abilities from Wowhead Forever pages."""

from __future__ import annotations

import argparse
import asyncio
import json
import re
import sys
from pathlib import Path
from typing import Iterable


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_STATE = ROOT / "Database" / "wowhead_abilities.json"
DEFAULT_LUA = ROOT / "Database" / "wowheadAbilities.lua"
NPC_ID_PATTERN = re.compile(r"(?:^|/)npc[=/](\d+)(?:/|[?#]|$)", re.IGNORECASE)
SPELL_ID_PATTERN = re.compile(r"/spell=(\d+)", re.IGNORECASE)
ABILITY_COUNT_PATTERN = re.compile(r"\((\d+)\)")


def parse_npc_reference(value: str) -> int:
    value = value.strip()
    if value.isdigit():
        npc_id = int(value)
    else:
        match = NPC_ID_PATTERN.search(value)
        if not match:
            raise ValueError(f"Expected an NPC ID or Wowhead NPC URL, got: {value!r}")
        npc_id = int(match.group(1))
    if npc_id <= 0:
        raise ValueError(f"NPC ID must be positive, got: {value!r}")
    return npc_id


def parse_spell_links(links: Iterable[tuple[str, str]]) -> list[dict[str, int | str]]:
    abilities: list[dict[str, int | str]] = []
    seen_spell_ids: set[int] = set()
    for href, name in links:
        match = SPELL_ID_PATTERN.search(href)
        spell_name = " ".join(name.split())
        if not match or not spell_name:
            continue
        spell_id = int(match.group(1))
        if spell_id in seen_spell_ids:
            continue
        seen_spell_ids.add(spell_id)
        abilities.append({"name": spell_name, "spellID": spell_id})
    return abilities


def load_state(path: Path) -> dict[str, list[dict[str, int | str]]]:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError(f"Could not read importer state {path}: {error}") from error
    if not isinstance(data, dict):
        raise ValueError(f"Importer state must be a JSON object: {path}")

    state: dict[str, list[dict[str, int | str]]] = {}
    for npc_id, abilities in data.items():
        if not isinstance(npc_id, str) or not npc_id.isdigit() or not isinstance(abilities, list):
            raise ValueError(f"Invalid NPC entry in importer state: {npc_id!r}")
        for ability in abilities:
            if (
                not isinstance(ability, dict)
                or not isinstance(ability.get("name"), str)
                or not isinstance(ability.get("spellID"), int)
                or isinstance(ability.get("spellID"), bool)
                or ability["spellID"] <= 0
            ):
                raise ValueError(f"Invalid ability entry for NPC {npc_id}")
        if int(npc_id) <= 0:
            raise ValueError(f"Invalid NPC ID in importer state: {npc_id}")
        state[npc_id] = abilities
    return state


def lua_quote(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def render_lua(state: dict[str, list[dict[str, int | str]]]) -> str:
    lines = [
        "local _, addon = ...",
        "",
        "-- Generated by tools/update_wowhead_abilities.py.",
        "",
    ]
    for npc_id in sorted(state, key=int):
        abilities = state[npc_id]
        if not abilities:
            continue
        lines.append(f"addon.Abilities[{npc_id}] = {{")
        for ability in abilities:
            lines.append(
                f"    {{ name = {lua_quote(str(ability['name']))}, "
                f"spellID = {int(ability['spellID'])} }},"
            )
        lines.extend(["}", ""])
    return "\n".join(lines)


def read_input_file(path: Path) -> list[str]:
    try:
        return [
            line.strip()
            for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.lstrip().startswith("#")
        ]
    except OSError as error:
        raise ValueError(f"Could not read input file {path}: {error}") from error


async def scrape_npc(page, npc_id: int) -> list[dict[str, int | str]]:
    url = f"https://www.wowhead.com/forever/npc={npc_id}"
    response = await page.goto(url, wait_until="domcontentloaded", timeout=45_000)
    if response is not None and response.status >= 400:
        raise RuntimeError(f"Wowhead returned HTTP {response.status} for NPC {npc_id}")

    reject_button = page.get_by_role("button", name="Reject All", exact=True)
    if await reject_button.count() and await reject_button.is_visible():
        await reject_button.click(force=True)

    abilities_tab = page.locator('button[role="tab"][data-href="#abilities"]')
    if not await abilities_tab.count():
        if (await page.title()).endswith(" - NPC - Forever"):
            return []
        raise RuntimeError(f"Wowhead page for NPC {npc_id} has no abilities tab")

    tab_label = await abilities_tab.first.inner_text()
    count_match = ABILITY_COUNT_PATTERN.search(tab_label)
    expected_count = int(count_match.group(1)) if count_match else None
    await abilities_tab.first.click(force=True)

    panel = page.locator("#tab-abilities")
    await panel.wait_for(state="visible", timeout=15_000)
    spell_links = panel.locator('a[href*="/forever/spell="]')
    await page.wait_for_timeout(750)
    links = await spell_links.evaluate_all(
        """anchors => anchors.map(anchor => [
            anchor.getAttribute("href") || "",
            anchor.innerText || ""
        ])"""
    )
    abilities = parse_spell_links((href, name) for href, name in links)

    if expected_count is not None and len(abilities) != expected_count:
        raise RuntimeError(
            f"NPC {npc_id}: Wowhead reports {expected_count} abilities, "
            f"but the page yielded {len(abilities)} distinct spell links"
        )
    if expected_count is None and not abilities:
        raise RuntimeError(f"NPC {npc_id}: no ability count or spell links found")
    return abilities


async def import_abilities(
    npc_ids: list[int], state: dict[str, list[dict[str, int | str]]], headed: bool, delay: float
) -> dict[str, list[dict[str, int | str]]]:
    try:
        from playwright.async_api import async_playwright
    except ImportError as error:
        raise RuntimeError(
            "Playwright is missing. Install it with "
            "`py -m pip install -r tools\\requirements.txt` and "
            "`py -m playwright install chromium`."
        ) from error

    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(headless=not headed)
        page = await browser.new_page()
        try:
            for index, npc_id in enumerate(npc_ids):
                abilities = await scrape_npc(page, npc_id)
                state[str(npc_id)] = abilities
                print(f"NPC {npc_id}: imported {len(abilities)} abilities")
                if index + 1 < len(npc_ids):
                    await asyncio.sleep(delay)
        finally:
            await browser.close()
    return state


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = path.with_suffix(path.suffix + ".tmp")
    temporary_path.write_text(content, encoding="utf-8", newline="\n")
    temporary_path.replace(path)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Import abilities for selected NPCs from Wowhead Forever pages."
    )
    parser.add_argument(
        "--npc",
        action="append",
        default=[],
        metavar="ID_OR_URL",
        help="NPC ID or Wowhead Forever NPC URL; repeat for multiple NPCs",
    )
    parser.add_argument(
        "--input",
        type=Path,
        help="Text file with one NPC ID or Wowhead NPC URL per line",
    )
    parser.add_argument("--state-file", type=Path, default=DEFAULT_STATE)
    parser.add_argument("--lua-file", type=Path, default=DEFAULT_LUA)
    parser.add_argument("--delay", type=float, default=1.5, help="Seconds between NPC pages")
    parser.add_argument("--headed", action="store_true", help="Show the Chromium window")
    parser.add_argument("--dry-run", action="store_true", help="Do not write state or Lua files")
    return parser


async def run(args: argparse.Namespace) -> int:
    if args.delay < 0:
        raise ValueError("--delay cannot be negative")

    raw_references = list(args.npc)
    if args.input:
        raw_references.extend(read_input_file(args.input))
    if not raw_references:
        raise ValueError("Provide at least one --npc value or --input file")

    npc_ids: list[int] = []
    for reference in raw_references:
        npc_id = parse_npc_reference(reference)
        if npc_id not in npc_ids:
            npc_ids.append(npc_id)

    state = load_state(args.state_file)
    state = await import_abilities(npc_ids, state, args.headed, args.delay)
    if args.dry_run:
        print(f"Dry run: would update {args.state_file} and {args.lua_file}")
        return 0

    write_atomic(args.state_file, json.dumps(state, ensure_ascii=False, indent=2) + "\n")
    write_atomic(args.lua_file, render_lua(state))
    print(f"Updated {args.state_file} and {args.lua_file}")
    return 0


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    try:
        return asyncio.run(run(args))
    except (ValueError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
